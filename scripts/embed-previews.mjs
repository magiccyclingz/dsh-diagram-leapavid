import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Inlines the per-type preview thumbnails into client.js as data URIs, between the
 * PREVIEWS:BEGIN / PREVIEWS:END markers.
 *
 * Two sizes are embedded per type:
 *   PREVIEWS       src/previews/<slug>.webp        480x300   list cards
 *   PREVIEWS_DETAIL src/previews/<slug>@detail.webp 1760x1100 detail page + zoom
 *
 * Regenerate the .webp files themselves with scripts/build-previews.sh (renders the
 * official example-<slug>.html pages from the diagram-design repo in headless Chrome
 * at 2x, trims the canvas to its content, and letterboxes it into both sizes).
 */
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const previews = path.join(root, 'src', 'previews');
const map = JSON.parse(fs.readFileSync(path.join(root, 'src', 'preview-map.json'), 'utf8'));

function entriesFor(suffix, mime) {
  return map.map(function (t) {
    const file = path.join(previews, t.slug + suffix);
    if (!fs.existsSync(file)) throw new Error('missing preview: ' + file);
    const b64 = fs.readFileSync(file).toString('base64');
    return '      ' + JSON.stringify(t.slug) + ': "data:image/webp;base64,' + b64 + '"';
  });
}

const block = [
  '    /* PREVIEWS:BEGIN - generated by scripts/embed-previews.mjs, do not edit */',
  '    var PREVIEWS = {',
  entriesFor('.webp').join(',\n'),
  '    };',
  '    var PREVIEWS_DETAIL = {',
  entriesFor('@detail.webp').join(',\n'),
  '    };',
  '    /* PREVIEWS:END */',
].join('\n');

const target = path.join(root, 'client.js');
let src = fs.readFileSync(target, 'utf8');
const re = /[ \t]*\/\* PREVIEWS:BEGIN[\s\S]*?PREVIEWS:END \*\//;
if (!re.test(src)) throw new Error('PREVIEWS markers not found in client.js');
src = src.replace(re, block);
fs.writeFileSync(target, src);
console.log('embedded ' + map.length + ' thumbs + ' + map.length + ' details -> client.js ' + Math.round(fs.statSync(target).size / 1024) + ' KB');
